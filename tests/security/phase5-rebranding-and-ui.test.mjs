import { describe, it } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();

function readRepoFile(relPath) {
  return fs.readFileSync(path.join(ROOT, relPath), "utf8");
}

describe("Phase 5 Security & Rebranding Suite — CounterCub Brand, Public Website & Audited Support Impersonation UI", () => {
  it("1. verifies core brand component, metadata, sitemap, robots, health API, and PWA manifest use CounterCub", () => {
    const logoSrc = readRepoFile("components/ui/SeyalLogo.tsx");
    assert.match(logoSrc, /Counter<span className="text-blue-400 font-black">Cub<\/span>/);
    assert.match(logoSrc, /export const CounterCubLogo = SeyalLogo/);

    const layoutSrc = readRepoFile("app/layout.tsx");
    assert.match(layoutSrc, /CounterCub — Business Operating System/);
    assert.match(layoutSrc, /https:\/\/www\.countercub\.com/);
    assert.doesNotMatch(layoutSrc, /SeyalPro/);

    const robotsSrc = readRepoFile("app/robots.ts");
    assert.match(robotsSrc, /https:\/\/www\.countercub\.com/);

    const sitemapSrc = readRepoFile("app/sitemap.ts");
    assert.match(sitemapSrc, /https:\/\/www\.countercub\.com/);

    const manifestSrc = readRepoFile("public/manifest.json");
    assert.match(manifestSrc, /"short_name":\s*"CounterCub"/);
    assert.doesNotMatch(manifestSrc, /SeyalPro/);

    const healthSrc = readRepoFile("app/api/health/route.ts");
    assert.match(healthSrc, /service:\s*"countercub"/);
  });

  it("2. verifies official public landing page (www.countercub.com) and login portals use CounterCub", () => {
    const landingSrc = readRepoFile("components/marketing/CounterCubLandingPage.tsx");
    assert.match(landingSrc, /Zero-Trust Multi-Tenant Retail &amp; Cafe Operating System/);
    assert.match(landingSrc, /validateTenantSlug/);
    assert.match(landingSrc, /\.countercub\.com\/login/);

    const homeSrc = readRepoFile("app/page.tsx");
    assert.match(homeSrc, /CounterCubLandingPage/);
    assert.doesNotMatch(homeSrc, /includes\("admin"\)/);

    const loginSrc = readRepoFile("app/login/page.tsx");
    assert.match(loginSrc, /<span className=\{styles\.wordmarkSeyal\}>Counter<\/span>/);
    assert.match(loginSrc, /<span className=\{styles\.wordmarkPro\}>Cub<\/span>/);

    const saLoginSrc = readRepoFile("app/super-admin/login/page.tsx");
    assert.match(saLoginSrc, /CounterCub Command Center/);
    assert.match(saLoginSrc, /admin@countercub\.com/);
    assert.doesNotMatch(saLoginSrc, /SeyalPro/);
  });

  it("3. verifies Super Admin portal uses CounterCub subdomains and Audited Support Impersonation Modal (no ?tenant= or cookie overrides)", () => {
    const saSrc = readRepoFile("app/(protected)/super-admin/page.tsx");
    assert.match(saSrc, /CounterCub Super Admin Portal/);
    assert.match(saSrc, /\.countercub\.com/);
    assert.doesNotMatch(saSrc, /\.seyalpro\.in/);
    assert.doesNotMatch(saSrc, /\/\?tenant=/);
    assert.doesNotMatch(saSrc, /document\.cookie\s*=\s*`tenant_slug=/);
    assert.match(saSrc, /\/api\/super-admin\/impersonation/);
    assert.match(saSrc, /Zero-Trust Audited Support Access/);
  });

  it("4. verifies PDF generators and WhatsApp templates are rebranded to CounterCub", () => {
    const billPdfSrc = readRepoFile("lib/utils/billPdf.ts");
    assert.match(billPdfSrc, /Powered by CounterCub App/);
    assert.doesNotMatch(billPdfSrc, /SeyalPro/);

    const ledgerPdfSrc = readRepoFile("lib/utils/combinedLedgerPdf.ts");
    assert.match(ledgerPdfSrc, /Powered by CounterCub App \(countercub\.com\)/);
    assert.doesNotMatch(ledgerPdfSrc, /SeyalPro/);

    const payslipSrc = readRepoFile("lib/utils/payslip.ts");
    assert.match(payslipSrc, /Generated by CounterCub System/);
    assert.doesNotMatch(payslipSrc, /SeyalPro/);

    const statementPdfSrc = readRepoFile("lib/utils/statementPdf.ts");
    assert.match(statementPdfSrc, /Generated electronically via CounterCub/);
    assert.doesNotMatch(statementPdfSrc, /SeyalPro/);

    const waPayslipSrc = readRepoFile("components/admin/WhatsAppPayslipModal.tsx");
    assert.match(waPayslipSrc, /_Generated via CounterCub Portal\._/);
  });
});

